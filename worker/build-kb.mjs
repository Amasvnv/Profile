/**
 * Regenerates worker/kb.js from data.js so the chat API always answers from
 * the same content the website shows. Run after editing data.js:
 *
 *   node worker/build-kb.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import vm from "node:vm";

const dataUrl = new URL("../data.js", import.meta.url);
const ctx = {};
vm.createContext(ctx);
vm.runInContext(
  readFileSync(dataUrl, "utf8") +
    "\nthis.__D = { EXPERIENCE, SKILL_GROUPS, CERTIFICATES, PROJECTS };",
  ctx,
);
const { EXPERIENCE, SKILL_GROUPS, CERTIFICATES, PROJECTS } = ctx.__D;

const clip = (text, max) => {
  const clean = String(text || "").replace(/\s+/g, " ").trim();
  return clean.length > max ? clean.slice(0, max - 1) + "…" : clean;
};

const lines = [];
lines.push(
  "PERSON: Hongkham Suvannavong (Lao name: ຫົງຄຳ ສຸວັນນະວົງ). IT support / system administrator / database and dashboard developer. 10+ years in Vientiane, Laos. Speaks Lao (native), Thai (fluent), English (working).",
);
lines.push(
  "CONTACT: primary email hongkham.svnv@outlook.com, second email hongkhamsuvannavong@gmail.com, phone and WhatsApp +856 20 5885 5817, based in Vientiane, Laos.",
);
lines.push("");

lines.push(`WORK EXPERIENCE (${EXPERIENCE.length} roles, newest first):`);
for (const item of EXPERIENCE) {
  lines.push(
    `- ${item.period} | ${item.title} — ${clip(item.subtitle, 90)} | ${item.kind} | ${item.location}`,
  );
  const points = (item.responsibilities || []).slice(0, 3).map((r) => clip(r, 110));
  if (points.length) lines.push(`  key work: ${points.join("; ")}`);
}
lines.push("");

lines.push(`PROJECTS (${PROJECTS.length} total):`);
for (const project of PROJECTS) {
  lines.push(
    `- ${project.title} | ${project.period} | ${project.status} | ${project.location} | ${clip(project.description, 200)}`,
  );
  if (project.tech && project.tech.length) {
    lines.push(`  tech: ${project.tech.join(", ")}`);
  }
  if (project.impact) lines.push(`  impact: ${clip(project.impact, 120)}`);
}
lines.push("");

lines.push(`CERTIFICATES (${CERTIFICATES.length}):`);
for (const cert of CERTIFICATES) {
  lines.push(`- ${cert.title} | ${cert.issuer} | ${cert.date}${cert.focus ? " | " + clip(cert.focus, 60) : ""}`);
}
lines.push("");

lines.push("SKILLS:");
for (const group of SKILL_GROUPS) {
  const names = group.skills.map((s) => `${s.name} (${s.level}%)`).join(", ");
  lines.push(`- ${group.title} / ${group.subtitle}: ${names}`);
}

const kb = lines.join("\n");
if (kb.includes("`") || kb.includes("${")) {
  throw new Error("Knowledge base contains characters that break the template literal");
}

writeFileSync(
  new URL("./kb.js", import.meta.url),
  `/* Generated by build-kb.mjs from ../data.js — do not edit by hand. */\nexport const KB = \`\n${kb}\n\`;\n`,
  "utf8",
);

console.log(
  `kb.js written: ${PROJECTS.length} projects, ${EXPERIENCE.length} roles, ${CERTIFICATES.length} certificates, ${SKILL_GROUPS.length} skill groups, ${Math.round(kb.length / 1024)} KB`,
);
